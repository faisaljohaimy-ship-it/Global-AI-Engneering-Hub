    def remux(self, work, audio, name, language="ara"):
        target = work / name
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(self.out / "show-test.mp4"), "-i", str(audio),
                        "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-ac", "2",
                        "-metadata:s:a:0", f"language={language}", "-movflags", "+faststart", str(target)], check=True, timeout=120)
        return target

    def failed(self, path, expect):
        report = vp.qa_media(path, expect)
        return report, {name for name, check in report["checks"].items() if not check["passed"]}

    def test_qa_catches_a_missing_voice(self):
        work, _, expect = self.expect()
        raw, master = work / "bed.wav", work / "bed-master.wav"
        vp.synthesize_audio(self.sb, raw, clips=[])                 # the same film, but nobody speaks
        vp.master_loudness(raw, master)
        report, failed = self.failed(self.remux(work, master, "no-voice.mp4"), expect)
        self.assertEqual(failed, {"voice.present_in_every_voiced_scene", "voice.speech_over_bed"})
        self.assertTrue(all(row["explained"] < 0.2 for row in report["voice"]))
