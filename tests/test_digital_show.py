def synthetic_voice(path, seconds, seed=1, *, rate=22050, channels=1, lead=0.25, tail=0.3, level=0.6):
    """SYNTHETIC stand-in for a narration clip: syllable-shaped bursts of a harmonic tone plus a little
    noise, with silence before and after. Clearly not speech."""
    total = int((lead + seconds + tail) * rate)
    data = array.array("h")
    state = (seed * 2654435761) & 0xFFFFFFFF or 1
    for i in range(total):
        t = i / rate - lead
        value = 0.0
        if 0 <= t < seconds:
            syllable = max(0.0, math.sin(2 * math.pi * 3.1 * t)) ** 1.5
            pitch = 118 + 14 * math.sin(2 * math.pi * 0.7 * t + seed)
            tone = sum(math.sin(2 * math.pi * pitch * k * t + k * k * 0.9) / k for k in range(1, 9))
            state ^= (state << 13) & 0xFFFFFFFF
            state ^= state >> 17
            state ^= (state << 5) & 0xFFFFFFFF
            noise = (state / 2147483648.0 - 1.0) * 0.12
            edge = min(1.0, t / 0.04, (seconds - t) / 0.04)
            value = (tone * 0.3 + noise) * syllable * edge * level
        sample = int(max(-1.0, min(1.0, value)) * 32767)
        data.extend([sample] * channels)
    with wave.open(str(path), "wb") as stream:
        stream.setnchannels(channels)
        stream.setsampwidth(2)
        stream.setframerate(rate)
        stream.writeframes(data.tobytes())
    return path


def synthetic_music(path, seconds, *, rate=44100):
    """SYNTHETIC music bed: two detuned chords, stereo."""
    data = array.array("h")
    for i in range(int(seconds * rate)):
        t = i / rate
        left = sum(math.sin(2 * math.pi * f * t) for f in (220.0, 277.2, 329.6)) / 3
        right = sum(math.sin(2 * math.pi * f * t) for f in (220.9, 278.0, 331.0)) / 3
        swell = 0.6 + 0.4 * math.sin(2 * math.pi * 0.5 * t)
        data.extend([int(left * swell * 12000), int(right * swell * 12000)])
    with wave.open(str(path), "wb") as stream:
        stream.setnchannels(2)
        stream.setsampwidth(2)
        stream.setframerate(rate)
        stream.writeframes(data.tobytes())
    return path


