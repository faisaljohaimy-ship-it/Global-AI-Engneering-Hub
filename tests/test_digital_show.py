@contextlib.contextmanager
def patched(mapping, **values):
    old = {key: mapping[key] for key in values}
    mapping.update(values)
    try:
        yield
    finally:
        mapping.update(old)


def read_stereo(path):
    with wave.open(str(path)) as stream:
        data = array.array("h", stream.readframes(stream.getnframes()))
    return [x / 32768 for x in data[0::2]], [x / 32768 for x in data[1::2]]


def rms(values):
    return math.sqrt(sum(x * x for x in values) / max(1, len(values)))


