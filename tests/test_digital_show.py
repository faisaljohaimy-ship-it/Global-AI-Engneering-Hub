        sb = vp.validate_storyboard(show_storyboard())
        report = vp.direct(sb)
        self.assertTrue(report["passed"], report["errors"])
        meanings = [c for c in report["checks"] if c["id"] == "semantic.meaning"]
        self.assertEqual([c["scene"] for c in meanings], ["s01-journey", "s02-gate", "s03-vision"])
        self.assertTrue(all(c["status"] == "pass" and vp._ARABIC.search(c["value"]) for c in meanings))
        ids = {c["id"] for c in report["checks"]}
        self.assertTrue({"reading.label_ms", "labels.primary_language", "reading.scene_density", "reading.cps.ar"} <= ids)
        self.assertNotIn("reading.cps.en", ids, "the English line is not on screen, so nobody has to read it there")
        self.assertNotIn("music.cut_on_beat", ids, "a voice-led edit is not judged against the beat")

