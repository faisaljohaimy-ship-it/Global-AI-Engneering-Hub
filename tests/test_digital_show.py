    def test_voice_is_centred_and_the_bed_is_ducked_under_it(self):
        fitted = vp.fit_storyboard_to_voice(show_storyboard(), str(self.voice))
        sb, clips, path, facts = self.mix(fitted)
        self.assertEqual(facts["mix"]["kind"], "voice-led")
        self.assertEqual(facts["samples"], vp.build_plan(sb)["frames"] * 1600)
        left, right = read_stereo(path)
        _, _, open_path, open_facts = self.mix(fitted, clips=[], name="open.wav")   # the same bed with nobody speaking
        open_left, open_right = read_stereo(open_path)
        scale = 10 ** (facts["mix"]["pre_master_scale_db"] / 20)
        open_scale = 10 ** (open_facts["mix"]["pre_master_scale_db"] / 20)
        times = vp.scene_times(sb)
        for clip, row in zip(clips, facts["voiceover"]):
            at = row["start_sample"]
            self.assertEqual(at, times[clip["scene"]]["start_frame"] * 1600 + 350 * 48)
            self.assertEqual(row["end_before_cut_ms"], round((row["cut_sample"] - at - len(clip["samples"])) / 48, 1))
            self.assertGreaterEqual(row["end_before_cut_ms"], 450)
            self.assertLess(row["end_before_cut_ms"], 550)
            self.assertGreaterEqual(row["speech_over_bed_db"], vp.VOICE["bed_under_speech_db"] - 0.01)
            self.assertLessEqual(row["duck_floor_db"], vp.VOICE["duck_floor_db"])
            n = len(clip["samples"])
            voice = [x * scale for x in clip["samples"]]
            # Centred: the voice is identical in both channels, so it cancels in left - right.
            side = [(left[at + i] - right[at + i]) for i in range(n)]
            mid = [(left[at + i] + right[at + i]) / 2 for i in range(n)]
            self.assertLess(rms([m - v for m, v in zip(mid, voice)]), rms(voice) * 0.2)
            self.assertLess(rms(side), rms(voice) * 0.2)
            # Ducking measured: what is left after removing the voice, against the open bed at the same place.
            ducked = rms([m - v for m, v in zip(mid, voice)]) / scale
            unducked = rms([(open_left[at + i] + open_right[at + i]) / 2 for i in range(n)]) / open_scale
            depth = 20 * math.log10(ducked / unducked)
            self.assertAlmostEqual(depth, row["duck_floor_db"], delta=1.5)
            self.assertLessEqual(depth, -10.0)
            self.assertGreaterEqual(20 * math.log10(rms(voice) / (ducked * scale)), 12.0)
        # Between the lines the bed comes back up: louder around the cut than under the speech.
        cut = facts["voiceover"][0]["cut_sample"]
        middle = facts["voiceover"][0]["start_sample"] + 48000
        speech_mid = [x * scale for x in clips[0]["samples"][48000:48000 + 9600]]
        under = rms([(left[middle + i] + right[middle + i]) / 2 - speech_mid[i] for i in range(9600)])
        between = rms([(left[cut - 2400 + i] + right[cut - 2400 + i]) / 2 for i in range(2400)])
        self.assertGreater(between, under * 1.5)
        again = self.mix(fitted, name="again.wav")[2]
        self.assertEqual(hashlib.sha256(path.read_bytes()).digest(), hashlib.sha256(again.read_bytes()).digest())

