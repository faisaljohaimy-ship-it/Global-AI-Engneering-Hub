class DuckingTests(unittest.TestCase):
    def test_envelope_is_a_pure_function_of_where_speech_is(self):
        spans, floors = [(48000, 96000), (150000, 170000)], [0.25, 0.1]
        first = vp.duck_envelope(240000, spans, floors)
        self.assertEqual(first, vp.duck_envelope(240000, spans, floors))
        attack, hold, release = (vp.VOICE[k] * 48 for k in ("duck_attack_ms", "duck_hold_ms", "duck_release_ms"))
        self.assertEqual(set(first[:48000 - attack]), {1.0})                     # open before the line
        self.assertEqual(first[48000 - attack], 1.0)
        self.assertEqual(set(first[48000:96000 + hold]), {0.25})                 # at the floor from the first speech sample
        fall = first[48000 - attack:48000]
        self.assertEqual(fall, sorted(fall, reverse=True))
        rise = first[96000 + hold:96000 + hold + release]
        self.assertEqual(rise, sorted(rise))
        self.assertAlmostEqual(first[96000 + hold + release], 1.0)
        self.assertEqual(set(first[150000:170000 + hold]), {0.1})
        self.assertEqual(min(first), 0.1)
        self.assertEqual(vp.duck_envelope(1000, [], []), [1.0] * 1000)
        clipped = vp.duck_envelope(1000, [(0, 990)], [0.5])                      # speech at the very edges stays in range
        self.assertEqual((len(clipped), clipped[0], clipped[-1]), (1000, 0.5, 0.5))

    def test_speech_activity_ignores_silence(self):
        tone = [0.5 * math.sin(2 * math.pi * 200 * i / 48000) for i in range(4800)]
        active = vp.speech_activity([0.0] * 4800 + tone + [0.0001] * 4800)
        self.assertEqual(active, [False] * 10 + [True] * 10 + [False] * 10)
        self.assertEqual(vp.speech_activity([0.0] * 4800), [False] * 10)


