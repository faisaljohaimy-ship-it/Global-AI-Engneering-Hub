#!/usr/bin/env node
// The L08 native-motion inventory, written to docs/evidence/gaie-20-layers/native-motions.json from
// what is on disk: the registry, the browser evidence and the brief. Nothing is typed in by hand,
// so the counts cannot drift from the code and the proof.
//
//   node packages/motion-engines/tools/native_inventory.mjs           rewrite the evidence file
//   node packages/motion-engines/tools/native_inventory.mjs --check   exit 1 if it is out of date
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brief, build, coreHash } from './build_registry.mjs';

const sdk = resolve(fileURLToPath(new URL('..', import.meta.url)));
const repo = resolve(sdk, '..', '..');
export const TARGET = join(repo, 'docs', 'evidence', 'gaie-20-layers', 'native-motions.json');
const sha256 = (data) => createHash('sha256').update(data).digest('hex');

/** The motions of PR #16, counted before this batch; they carry no digital meaning field. */
export const BASELINE_ENGINE_MOTIONS = 34;
/** The nextgen camera scenes of PR #25 (motion-library/expansion/nextgen-camera.mjs), counted separately by engineering_os/cinematic.py. */
export const NEXTGEN_CAMERA_IDS = Object.freeze(['camera-drone-approach', 'camera-infinite-flythrough', 'camera-macro-to-micro']);
/** Drafted in this batch, verified, then withdrawn because their meaning was only decorative (owner direction of 2026-11-28). */
export const WITHDRAWN = Object.freeze([
  'lighting-lens-flare', 'lighting-studio-spotlight', 'lighting-volumetric-beams', 'shaders-raymarched-geometry', 'shaders-sdf-morph',
]);

export async function inventory() {
  const { document } = await build();
  const evidencePath = join(sdk, 'evidence', 'chromium.json');
  const evidenceText = readFileSync(evidencePath, 'utf8');
  const evidence = JSON.parse(evidenceText);
  const rows = new Map(evidence.results.map((row) => [row.id, row]));
  const added = document.motions.filter((entry) => entry.meaning);
  const nativeEngine = document.motions.length;
  const overlap = document.motions.filter((entry) => NEXTGEN_CAMERA_IDS.includes(entry.id)).map((entry) => entry.id);
  const total = nativeEngine + NEXTGEN_CAMERA_IDS.length - overlap.length;
  return {
    schema_version: 1,
    layer: 'L08',
    notes: 'Generated by packages/motion-engines/tools/native_inventory.mjs from packages/motion-engines/registry.json, evidence/chromium.json and tools/brief.json. A motion counts only while its browser evidence matches its exact source and the current SDK core. Rendering was done by SwiftShader, a CPU implementation of WebGL2/WebGPU: no hardware GPU is claimed.',
    inputs: {
      registry_sha256: sha256(readFileSync(join(sdk, 'registry.json'), 'utf8')),
      evidence_sha256: sha256(evidenceText),
      core_sha256: coreHash(),
    },
    browser: { ...evidence.engine, generated_on: evidence.generated_on },
    gpu_hardware_claimed: false,
    counts: {
      target: brief.length,
      baseline: { native_engine_motions: BASELINE_ENGINE_MOTIONS, nextgen_camera_motions: NEXTGEN_CAMERA_IDS.length, total: BASELINE_ENGINE_MOTIONS + NEXTGEN_CAMERA_IDS.length },
      added_this_batch: added.length,
      added_operational: added.filter((entry) => entry.status === 'operational').length,
      native_engine_motions: nativeEngine,
      native_engine_operational: document.motions.filter((entry) => entry.status === 'operational').length,
      nextgen_camera_motions: NEXTGEN_CAMERA_IDS.length,
      native_total: total,
      remaining_to_target: brief.length - total,
      by_engine: added.reduce((totals, entry) => ({ ...totals, [entry.engine]: (totals[entry.engine] ?? 0) + 1 }), {}),
      by_module: added.reduce((totals, entry) => ({ ...totals, [entry.category.key]: (totals[entry.category.key] ?? 0) + 1 }), {}),
    },
    withdrawn_this_batch: WITHDRAWN.map((id) => ({ id, reason: 'decorative only: no digital meaning that can be stated in one sentence; removed before counting' })),
    remaining_brief_ids: brief.map((row) => row.id).filter((id) => !document.motions.some((entry) => entry.id === id) && !NEXTGEN_CAMERA_IDS.includes(id)),
    motions: added.map((entry) => {
      const row = rows.get(entry.id);
      return {
        id: entry.id,
        number: entry.number,
        name: entry.name,
        meaning: entry.meaning,
        engine: entry.engine,
        kind: entry.kind,
        rtl: entry.compatibility.rtl,
        reduced_motion: entry.reduced_motion,
        source: entry.source,
        source_sha256: entry.source_sha256,
        status: entry.status,
        proof: row ? {
          frame_signature: row.measured.signature,
          checks_passed: Object.values(row.checks).filter(Boolean).length,
          checks_total: Object.keys(row.checks).length,
          average_frame_ms: row.measured.benchmark?.averageMs ?? null,
          evidence: `packages/motion-engines/evidence/chromium.json#${entry.id}`,
        } : null,
      };
    }),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = JSON.stringify(await inventory(), null, 1) + '\n';
  if (process.argv.includes('--check')) {
    if (!existsSync(TARGET) || readFileSync(TARGET, 'utf8') !== text) {
      console.error('Out of date: docs/evidence/gaie-20-layers/native-motions.json. Run node packages/motion-engines/tools/native_inventory.mjs.');
      process.exit(1);
    }
  } else writeFileSync(TARGET, text);
  const { counts } = JSON.parse(text);
  console.log(JSON.stringify({ added: counts.added_this_batch, operational: counts.added_operational, native_total: counts.native_total, remaining: counts.remaining_to_target }));
}
