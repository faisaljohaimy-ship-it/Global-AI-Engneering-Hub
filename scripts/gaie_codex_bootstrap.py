#!/usr/bin/env python3
"""Render and verify the GAIE factory's Codex skills in a hub checkout.

Both commands are read-only. Render to a temporary file, then review the diff
before changing the tracked checkout projection. SPDX-License-Identifier: MIT.
"""

import argparse
import hashlib
import json
import pathlib
import re
import stat
import sys


ROOT = pathlib.Path(__file__).resolve().parents[1]
PACK = pathlib.Path("catalog/packs.json")
CODEX_SKILLS = pathlib.Path(".agents/skills")
SKILL_NAME = re.compile(r"gaie-[a-z0-9]+(?:-[a-z0-9]+)*")


def checked_path(root, relative, directory=False):
    """Require regular files and directories wherever the path already exists."""
    current = root
    for index, part in enumerate(relative.parts, start=1):
        current /= part
        try:
            mode = current.lstat().st_mode
        except FileNotFoundError:
            return root / relative
        expected = stat.S_ISDIR if directory or index < len(relative.parts) else stat.S_ISREG
        if not expected(mode):
            raise ValueError(f"refused non-regular path: {current.relative_to(root)}")
    return current


def skill_names(root):
    packs = json.loads(checked_path(root, PACK).read_bytes())
    names = packs["packs"]["gaie-factory"]["skills"]
    if not isinstance(names, list) or not names or any(
        not isinstance(name, str) or not SKILL_NAME.fullmatch(name) for name in names
    ):
        raise ValueError("invalid GAIE factory skill list")
    if len(names) != len(set(names)):
        raise ValueError("duplicate skill in the GAIE factory pack")
    return sorted(names)


def projection(root, name):
    relative = pathlib.Path("skills") / name / "SKILL.md"
    source = checked_path(root, relative).read_bytes()
    opening, boundary, rest = source.decode("utf-8").partition("\n")
    frontmatter, closing, _ = rest.partition("\n---\n")
    if opening != "---" or not boundary or not closing:
        raise ValueError(f"missing skill frontmatter: {relative}")
    names = [line.removeprefix("name: ") for line in frontmatter.splitlines() if line.startswith("name: ")]
    descriptions = [line.removeprefix("description: ") for line in frontmatter.splitlines()
                    if line.startswith("description: ")]
    if names != [name] or len(descriptions) != 1 or not descriptions[0].strip():
        raise ValueError(f"invalid skill name or description: {relative}")
    digest = hashlib.sha256(source).hexdigest()
    content = f"""---
name: {name}
description: {json.dumps(descriptions[0], ensure_ascii=False)}
---

<!-- Generated by scripts/gaie_codex_bootstrap.py. Source SHA-256 {digest}. -->

Use the GAIE hub checkout containing this skill. From the hub root, run
`python3 scripts/gaie_codex_bootstrap.py check`. If verification fails, report
which projection needs review and stop loading this skill.

Read `{relative.as_posix()}` in that checkout and apply its instructions to the
owner's request. Use its hub-checkout entry points. Apply the required grants and
execution boundaries through the current host and the GAIE control plane. For
Claude-specific install paths and subagent declarations, use the current host's
equivalent only when it enforces the required boundary.
"""
    if name == "gaie-master-router":
        content += """
For the canonical skill's routing step, run the Codex adapter from the hub root.

```sh
python3 -B -m scripts.gaie_codex_route -- "$gaie_owner_command"
```

Set `gaie_owner_command` to the exact owner request. Pass `--workspace <checkout>`
before `--` when validating a selected workspace. The adapter preserves the
canonical target, permissions and gates. It suggests Codex branch names and
refuses a verified Claude branch for a write plan. A branch suggestion grants
no authorization.
"""
    else:
        content += "\nUse the native `gaie-master-router` to create or re-check a Codex routing plan.\n"
    if name in {"gaie-master-router", "gaie-build", "gaie-upgrade"}:
        content += """
For build and upgrade, follow the canonical team policy. Use the native
`gaie_specialist` agent for assigned roles. Staff or record an omission for
every role, respect the effective host limit and preserve independent review.
"""
    if name == "gaie-audit":
        content += """
Use the Codex `gaie_verifier` only if the parent host has established read-only
filesystem access, disabled network access and disabled approval escalation for
the reviewer. Otherwise use the canonical governed `master-audit` path when
available. Stop if the required boundary cannot be verified.
"""
    return content.encode("utf-8"), digest


def verify(root, names):
    directory = checked_path(root, CODEX_SKILLS, directory=True)
    actual_names = {path.name for path in directory.glob("gaie-*")}
    unexpected = sorted(actual_names.difference(names))
    skills = {}
    for name in names:
        target = checked_path(root, CODEX_SKILLS / name / "SKILL.md")
        expected, digest = projection(root, name)
        try:
            actual = target.read_bytes()
        except FileNotFoundError:
            status = "missing"
        else:
            status = "current" if actual == expected else "drifted"
        skills[name] = {"status": status, "source_sha256": digest}
    return {"ok": not unexpected and all(item["status"] == "current" for item in skills.values()),
            "skills": skills, "unexpected": unexpected}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check", help="report missing or drifted projections without changing files")
    render = commands.add_parser("render", help="write one expected projection to stdout")
    render.add_argument("name")
    args = parser.parse_args(argv)
    try:
        names = skill_names(ROOT)
        if args.command == "render":
            if args.name not in names:
                raise ValueError(f"skill is outside the GAIE factory pack: {args.name}")
            sys.stdout.buffer.write(projection(ROOT, args.name)[0])
            return 0
        report = verify(ROOT, names)
    except (KeyError, OSError, TypeError, ValueError) as error:
        print(json.dumps({"ok": False, "error": str(error)}))
        return 1
    print(json.dumps(report, indent=2))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
